; =====================================================================================================================
; jumprun.asm - "Hugo & Gumbo": self-running jump-and-run demo for the Atari 8 bit (main program)
; =====================================================================================================================
;
; FLOW (endless):   title screen (8 seconds) -> level 1 meadow -> level 2 cave -> level 3 castle -> level 4 clouds
;                    -> finale (fanfare) -> title screen again.   No controls: the autopilot (core.asm) guides the hero
;                    Hugo, the game logic makes the enemy Gumbo run after him.  Music and sound effects play all the time.
;
; SOURCE LAYOUT
;   jumprun.asm              this main program (flow control, title screen)
;   hal_atari.asm            hardware layer: ANTIC/GTIA (screen, players/missiles), POKEY (sound), interrupts
;   lib/core.asm             game logic (platform-neutral; this project's own copy, independent of the other systems)
;   lib/rmt.inc, rmtplayr.asm  music player (Raster Music Tracker); rmtplayr.asm is the unchanged original player (third-party library)
;   lib/levels.inc           tables and player data (GENERATED by tools/gen_jumprun_atari.py)
;   graphics/*, music/       editor project files: character set chars.vcchar, title screen title.vcscreen, tile set hg.vctiles, screen bank levels.vcscreen,
;                            song tune.vcsong (converted during the build where it is included below)
;
; TIMING: In every pass the main program waits for the next vertical blank (hal_wait_frame); so everything runs at the
;   frame rate of the TV, 50 times per second (PAL; 60 on NTSC, where the demo runs correspondingly faster).
;   All times in this program ("400 frames = 8 seconds") are for PAL.
;
; MEMORY MAP
;   $2000-$3BFF  program      $3C00 character set   $4000 screen   $4800 display list   $5000-$57FF player memory
;   $5800 level map (LMAP)     $5CE0-$5FFF RMT tables   $6000 RMT player   $7000 tables, screen data, music module
;   Zero page: $80-$B3 game logic, $B4-$BB HAL, $CB-$DD RMT player
;   (State of this version: program $2000-$30EA, character set with tile tables $3B97-$3FFF, RMT player $6000-$6610, data and tile library $7000-$7E9F.  The display list
;   is not in the file but is copied from dlist_data to $4800 at start; screen and player memory are unused,
;   they are filled at run time.)
; =====================================================================================================================
.target atari8                          ; target system: Atari 8 bit; the result is an executable file in XEX format (segments + start address)
.cpu sally { illegals = deny }          ; CPU "Sally" (6502C in the Atari); undocumented instructions are forbidden
.branchlong auto                        ; too-far conditional branches are extended by the assembler itself (warning W203)

.const ZP   = $80                       ; zero page variables of the game logic (uses $80-$B3)
.const NO_SEI_BCD = 1                   ; core.asm: do_coin does not block IRQs here (the interrupts are NMIs, see do_coin)
.const LMAP = $5800                     ; level map in RAM (240 bytes = 20 x 12 tiles), coins are deleted from it
.const RMT_PLAYER = $6000               ; play routine of the music (tables before it)

; Tile library: draws the tiles (tile_put) and the screens (screen_select_a, screen_draw_all); the data comes from the export of
; graphics/hg.vctiles (tile set) and graphics/levels.vcscreen (screen bank), the binding is below at tiles_use.
.const TILE_MAPRAM = LMAP               ; screen_select_a copies the map of a screen to LMAP (coins are deleted there)
.const TILE_ZP = $bc                    ; zero page $BC-$C3 for the library (free: logic $80-$B3, HAL $B4-$BB, RMT $CB-$DD)
#include <atari8bit/tiles.asm>

.org $2000                              ; start of program: above the area that DOS and OS need for themselves
.include "lib/rmt.inc"                  ; macros for the music player (rmt_start ...)

; Program start (the XEX file starts here, see .run at the end): copy the display list to its fixed place, set up the hardware,
; start the music.  Unlike the other systems there is no sei/cli: the operating system keeps running, hal_init hooks into it.
;   The loop copies dlist_data (length dlist_end - dlist_data = 3 + 3 + 23 + 3 = 32 bytes) backwards from X = 31 to 0; bpl ends at
;   X = $FF.  Then hal_init sets up the chips, rmt_start hands the music module to the player (X/Y = address, A = start line).
;   From now on the HAL's vertical-blank interrupt calls the music in every frame, nothing more to do here.
start:  ldx #dlist_end - dlist_data - 1
-       lda dlist_data,x
        sta DLIST,x
        dex
        bpl -
        jsr hal_init
        rmt_start tune_rmt, 0           ; music from line 0 (the HAL calls the player in every frame)
        jmp main

cur:    .byte 0                         ; number of the current level (0..3); main counts it up, after level 3 comes the finale

; main: score to 0, title screen, four levels one after another, finale, start over.
;   The score has three BCD digits (sc0 low, sc2 high).  After the fourth level (cur = 4) comes the finale: fanfare (effect 7),
;   hold for 2 seconds (100 frames), screen off, wait 20 more frames, then start over with the title screen.
main:   lda #0
        sta sc0
        sta sc1
        sta sc2
        jsr show_title
        lda #0
        sta cur
.next:  lda cur
        jsr play_level
        inc cur
        lda cur
        cmp #4
        bcc .next
        lda #7                          ; finale: fanfare
        jsr hal_sfx
        ldx #100
        jsr wait_x
        jsr hal_blank
        ldx #20
        jsr wait_x
        jmp main

; wait_x: waits X frames; X is saved around the frame call.
;   X serves as counter; so that a register used by the called routine does not destroy it, it is kept on the stack
;   during the call (pha / pla).  X = 0 would mean 256 frames (dex wraps from 0 to 255).
wait_x: txa
        pha
        jsr hal_wait_frame
        pla
        tax
        dex
        bne wait_x
        rts

; ---------------------------------------------------------------- Title screen (8 seconds = 400 frames)
; Colors of the first level, prompt text (blinks: alternately text and spaces), both figures bob.
;   Flow: screen off; set the colors of level 0 (meadow) (same registers as hal_load_level, but without map and
;   status line); copy the title characters to the screen; set the game state of hero and enemy so that both stand (hmode, emode = 0);
;   draw sprites; screen on; let it blink and bob for 400 frames.
;   Unlike on the C64 there is no color RAM: the prompt blinks by swapping the characters (text <-> spaces).
;   This subroutine accesses DIRECTLY the shadow registers COLOR0.., the sky table skyc and the screen SCREEN of the HAL
;   and sets the core's state variables by hand (core_level_init does not run here).  Changes all registers.
show_title:
        jsr hal_blank
        lda #0
        sta lvl
        tax                             ; X = 0 = level number for the color tables
        lda lvl_pf0,x
        sta COLOR0                      ; COLPF0 (shadow register)
        lda lvl_pf1,x
        sta COLOR0+1                    ; COLPF1
        lda lvl_pf2,x
        sta COLOR0+2                    ; COLPF2
        lda lvl_sky0,x
        sta skyc                        ; bar 0 (hal_unblank sets it as COLOR4/COLBK; until then the background stays black)
        lda lvl_sky1,x
        sta skyc+1
        lda lvl_sky2,x
        sta skyc+2
        lda lvl_sky3,x
        sta skyc+3
        lda lvl_sky4,x
        sta skyc+4
        lda lvl_sky5,x
        sta skyc+5
        jsr hal_title
        lda #0                          ; hero left, enemy right, both standing
        sta hx_h
        sta hx_f
        sta hdir
        sta hmode
        sta hatim
        sta ex_f
        sta eatim
        sta emode
        lda #24
        sta hx_l                        ; hero x = 24 (logical points, left edge)
        lda #160
        sta hy                          ; foot y = 160 = top edge of tile row 10 (the grass row of the title screen)
        sta ey
        lda #<272
        sta ex_l                        ; enemy x = 272 (24 points wide: right edge at 296)
        lda #>272
        sta ex_h
        lda #1
        sta edir                        ; enemy faces left, towards Hugo
        jsr core_prepare_sprites
        jsr hal_update_sprites
        jsr hal_unblank
        lda #<400
        sta tmr_l
        lda #>400
        sta tmr_h                       ; 16-bit counter: 400 frames = 8 seconds
; Loop per frame: wait, show or erase the prompt text, let the figures bob, count down the counter.
;   Blinking: bit 5 of the counter changes every 32 frames (0.64 s text visible, 0.64 s invisible).  The 21 characters of
;   txt_prompt (or 21 spaces) go to row 18, column 9 (centered: (40 - 21) / 2 = 9).
.tf:    jsr hal_wait_frame
        lda tmr_l                       ; blinking: bit 5 of the counter selects text or spaces
        and #$20
        beq +
        ldx #20
-       lda txt_prompt,x
        sta SCREEN+18*40+9,x
        dex
        bpl -
        jmp ++
+       ldx #20
        lda #CH_BLANK
-       sta SCREEN+18*40+9,x
        dex
        bpl -
+       lda tmr_l                       ; figures bob slightly (bit 4 of the counter)
        lsr a
        lsr a
        lsr a
        lsr a
        and #1                          ; changes every 16 frames between 0 and 1
        clc
        adc #160                        ; foot y 160 or 161: the figures rise and sink by one point
        sta hy
        sta ey
        jsr core_prepare_sprites
        jsr hal_update_sprites
        lda tmr_l                       ; count the 16-bit counter down: if the low byte = 0, decrement the high byte first (borrow)
        bne +
        dec tmr_h
+       dec tmr_l
        lda tmr_l
        ora tmr_h                       ; both bytes 0? Then the 400 frames are over.
        bne .tf
        rts

; ---------------------------------------------------------------- Play one level: A = 0..3
; play_level (input A = level number 0..3, changes all registers): screen off -> initialize the game logic for this level ->
;   load screen and colors -> screen on ->
;   per frame: wait for frame end, move hero, move enemy, prepare values for the HAL, set sprites ->
;   when the autopilot has reached "END" (lvl_done), play a jingle (except after the last level), wait 70 frames.
;   The one frame of waiting before hal_unblank is just a short pause in the black screen (hal_blank has already switched off screen and
;   background); SDMCTL and COLOR4 from hal_unblank are taken over together in the next vertical blank.
play_level:
        pha                             ; save level number (hal_blank uses A)
        jsr hal_blank
        pla
        jsr core_level_init             ; game logic: positions, script, set lvl
        lda lvl
        jsr hal_load_level
        jsr core_prepare_sprites
        jsr hal_update_sprites
        ldx #1
        jsr wait_x
        jsr hal_unblank
.f:     jsr hal_wait_frame
        jsr hero_update
        jsr enemy_update
        jsr core_prepare_sprites
        jsr hal_update_sprites
        lda lvl_done
        beq .f
        lda cur                         ; door reached: jingle (not after the last level), wait briefly
        cmp #3
        beq +
        lda #6
        jsr hal_sfx
+       ldx #70
        jsr wait_x
        rts

; ---------------------------------------------------------------- Including the other sources and data
; Order in memory: HAL, game logic and tables follow directly after the main program (below $4000);
; the RMT player and the editor exports are placed at fixed addresses with .org (see the memory map above).
.include "hal_atari.asm"
.include "lib/core.asm"
.include "lib/levels.inc"

; Tile properties of the game logic (core.asm reads tile_attr,x): 0 empty, 1 solid (hg_p_solid), 2 ladder (hg_p_ladder) - from the tile set
.const tile_attr = hg_props
.assert hg_p_solid == 1 && hg_p_ladder == 2, "core.asm expects 1 = solid, 2 = ladder"

.org RMT_PLAYER
.include "lib/rmtplayr.asm"             ; original player; its tables lie directly before $6000 ($5CE0-$5FFF)

.org $3C00 - 105                        ; character set: 128 characters * 8 bytes = 1 KB, on a 1 KB boundary (ANTIC requirement). The export of the tile set puts
.include "graphics/hg.vctiles"          ; before hg_chars the tables (4 x 21 characters, 21 properties = 105 bytes); hg_chars is the character set chars.vcchar (all characters pinned)
.assert hg_chars == $3C00, "Zeichensatz muss bei $3C00 liegen (Tabellen des Kachelsatzes davor, siehe .org)"
.org $7000                              ; title screen, maps and music module (title_chars, levels_map0..3, tune_rmt)
.include "graphics/title.vcscreen"
.include "graphics/levels.vcscreen"
.include "music/tune.vcsong"

; Binding of the library to tile set and screen bank (no color memory: column col is omitted), then the subroutines
        tiles_use hg_c0, 0, hg_props, hg_tw, hg_th, hg_count, levels_screens_lo, levels_screens_hi, levels_lv1_tiles_w, levels_lv1_tiles_h
        tiles_runtime
.run start                              ; start address of the XEX file (RUNAD $02E0): the program starts at start
