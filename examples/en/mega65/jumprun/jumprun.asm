; =====================================================================================================================
; jumprun.asm - "Hugo & Gumbo": self-playing jump-and-run demo for the MEGA65 (main program)
; =====================================================================================================================
;
; FLOW (endless):   title screen (8 seconds)  ->  level 1 meadow -> level 2 cave -> level 3 castle -> level 4 clouds
;                    ->  finale (fanfare)  ->  the title screen again.
;   There is no control: the "autopilot" (core.asm) guides the hero Hugo, the game logic makes the enemy Gumbo
;   run after him.  Music and sound effects play all the time.
;
; SOURCE LAYOUT
;   jumprun.asm              this main program (flow control, title screen)
;   hal_mega65.asm           hardware layer: VIC-II mode of the VIC-IV (screen, sprites), two SIDs (sound), interrupt
;   lib/core.asm             game logic (platform neutral; own copy for this project, independent of the other systems)
;   lib/music.inc            player routine for the tracker music (SID 1 at $D400, 3 voices; on the MEGA65 the sound effects
;                            run on the second SID, so the music never has to pause)
;   lib/levels.inc           tables: tile properties, colors, start positions, autopilot scripts, texts
;                            (GENERATED by tools/gen_jumprun_c64.py from the art data tools/jumprun_art.py; the art data is
;                            that of the C64 example, only the target system and profiles are MEGA65)
;   graphics/*, music/       project files of the editors: character set chars.vcchar, tile maps lv1..lv4.vctiles, title screen title.vcscreen,
;                            sprites (hero_*, enemy_*.vcsprite), song tune.vcsong
;                            (when building, the assembler converts them itself where they are included below)
;   Unlike on the C64 there is no tile library here: hal_mega65.asm draws the tiles itself (hal_draw_level) and
;   only knows the tile list lv1_tiles/lv1_colors; the level maps lv1..lv4 are available as 240-byte maps (maps_lo/hi below).
;
; THIS VERSION is "stage 1" for the MEGA65: pure C64 code (6502 instructions) that runs in the VIC-II mode of the new video chip
;   (VIC-IV).  The MEGA65 starts differently from the C64: BASIC 65 has remapped the memory via MAP and set up the video chip
;   differently; hal_init (hal_mega65.asm) therefore first restores a plain 64 KB RAM state with I/O
;   at $D000 ($01 = $35) and switches the VIC-IV back to 40 columns.  Hence also the different addresses than on the C64:
;   the program starts at $2001 (BASIC 65 start address), and the data the VIC has to read lies in VIC bank 1.
;
; MEMORY MAP
;   $2001-$3FFF  program (BASIC starter + code; up to $2F2E in this version)        $6000-$67FF  character set (from chars.vcchar)
;   $6800-$71FF  sprites (4 sets, see below)            $7200-$80D1  title screen, tile maps, music data (as of this version; the data
;                                                                    from $8000 on lies outside the VIC bank, but is only read by the CPU)
;   $9000-$90EF  level map in RAM (LMAP)                $4400-$47E7  screen (VIC bank 1 = $4000-$7FFF), sprite pointers $47F8
;   Zero page: $10-$43 game logic, $50-$56 HAL, $F7-$FA music        Color RAM: $D800 (hires text: color value < 8)
;   Between $4000 and $5FFF there is only the screen at $4400; the rest of bank 1 up to $5FFF is unused.
; =====================================================================================================================
.target mega65                          ; Target system: MEGA65 (chip and memory map of the MEGA65 for the assembler and the IDE)
.cpu 45gs02 { illegals = deny }         ; CPU 45GS02 (6502 compatible; additionally map, eom, taz etc.); undocumented instructions are forbidden
.branchlong auto                        ; the assembler itself lengthens conditional branches that are too far (warning W203)

.const ZP   = $10                       ; zero-page variables of the game logic start at $10
.const LMAP = $9000              ; level map in RAM (240 bytes), coins are deleted from it

.org $2001                              ; BASIC 65 start address (on the C64 it is $0801): a PRG is loaded here
.basicstub start                        ; creates the BASIC line "10 SYS <address of start>" so that RUN starts the program
                                        ; (so the code first runs in the BASIC 65 environment; hal_init clears it away first of all)

.include "lib/music.inc"

; Program start: set up the hardware, start the music (music_init points the player routine at the exported song data).
start:  jsr hal_init                    ; memory map (MAP), $01, VIC-IV unlock, VIC bank 1, sprites, interrupt vector, SID 2
        music_init tune_order, tune_patterns, tune_ins, tune_speed, tune_rows, tune_patsize
        cli                             ; enable interrupts now: from here on the music and the frame clock run (vector $FFFE in RAM, see hal_init)
        jmp main                        ; main flow

; ---------------------------------------------------------------- Main flow
; cur = number of the running level (0..3)
cur:    .byte 0


; main: the main flow.  Score to 0, show the title screen, play the four levels one after another, finale, start over.
main:   lda #0
        sta sc0
        sta sc1
        sta sc2
        jsr show_title
        lda #0
        sta cur
.next:  lda cur
        jsr play_level
        inc cur
        lda cur
        cmp #4
        bcc .next
        ; Finale: fanfare, then back to the title screen
        lda #7
        jsr hal_sfx
        ldx #100
        jsr wait_x
        jsr hal_blank
        ldx #20
        jsr wait_x
        jmp main

; wait_x: waits X frames (X * 1/50 second, PAL).  X = 0 would give 256 frames.  X is saved around the call, because the
;   HAL interface does not guarantee that hal_wait_frame preserves X (this version only changes A).  Changes A, X (= 0) and flags.
wait_x:                          ; wait X frames
-       txa
        pha
        jsr hal_wait_frame
        pla
        tax
        dex
        bne -
        rts

; ---------------------------------------------------------------- Title screen (8 seconds = 400 frames)
; show_title: shows the title screen with the sky colors and multicolors of the first level, the blinking notice
;   "DEMO - NICHT SPIELBAR" (German text from levels.inc; row 18; blinking = alternating text color and sky color in the color RAM row) and both
;   characters, which bob slightly up and down.  The counter tmr_h:tmr_l counts down 400 frames.
;   This subroutine accesses the VIC registers ($D022/$D023), the sky table skyc and the HAL's screen/color RAM DIRECTLY
;   (the color choice corresponds to the start of hal_load_level) and sets the state variables of the core by hand (core_level_init
;   does not run here); it is therefore not system neutral.  Changes all registers.
show_title:
        jsr hal_blank
        lda #0
        sta lvl
        tax
        lda lvl_mc1,x
        sta $d022                       ; multicolor 1 of the first level
        lda lvl_mc2,x
        sta $d023                       ; multicolor 2 of the first level
        lda lvl_sky0,x
        sta skyc
        lda lvl_sky1,x
        sta skyc+1
        lda lvl_sky2,x
        sta skyc+2
        lda lvl_sky3,x
        sta skyc+3
        lda lvl_sky4,x
        sta skyc+4
        lda lvl_sky5,x
        sta skyc+5
        jsr hal_title
        ; Notice "DEMO - NICHT SPIELBAR" (German text, row 18, column 9, 21 characters), blinks via the color
        ldx #0
-       lda txt_prompt,x
        sta SCREEN+18*40+9,x            ; row 18, column 9 (screen $4400 + 18 * 40 + 9)
        inx
        cpx #21
        bne -
        ; hero on the left, enemy on the right, both standing
        lda #24
        sta hx_l
        lda #0
        sta hx_h
        sta hx_f
        sta hdir
        sta hmode
        sta hatim
        sta ex_f
        sta eatim
        sta emode
        lda #160
        sta hy
        sta ey
        lda #<272
        sta ex_l
        lda #>272
        sta ex_h
        lda #1
        sta edir
        jsr core_prepare_sprites
        jsr hal_update_sprites
        jsr hal_unblank
        lda #<400                ; 400 frames
        sta tmr_l
        lda #>400
        sta tmr_h
.tf:    jsr hal_wait_frame
        ; Blinking: bit 5 of the counter (tmr_l and $20) switches every 32 frames between yellow (7) and the sky color cyan (3)
        lda tmr_l
        and #$20
        beq +
        lda #7
        jmp ++
+       lda #3
+      ldx #0
-       sta COLOR+18*40+9,x             ; color RAM of the notice row (color values 7 / 3, both below 8: hires text)
        inx
        cpx #21
        bne -
        ; Characters bob slightly: bit 4 of the counter switches every 16 frames, foot y = 160 or 161
        lda tmr_l
        lsr a
        lsr a
        lsr a
        lsr a
        and #1
        clc
        adc #160
        sta hy
        sta ey
        jsr core_prepare_sprites
        jsr hal_update_sprites
        lda tmr_l                       ; count down the 16-bit counter: if the low byte is 0, decrement the high byte first (borrow)
        bne +
        dec tmr_h
+       dec tmr_l
        lda tmr_l
        ora tmr_h                       ; both bytes 0? Then the 400 frames are over.
        bne .tf
        rts

; ---------------------------------------------------------------- Play one level: A = 0..3
; play_level: screen off -> initialize the game logic for this level -> load picture and colors -> screen on ->
;   per frame: wait for the frame, move the hero, move the enemy, prepare values for the HAL, set the sprites ->
;   when the autopilot has reached "END" (lvl_done), play the jingle (except after the last level), wait 70 frames.
;   Input: A = level number 0..3 (also in cur).  Changes all registers.  The three frames of waiting before hal_unblank give the
;   interrupt time to take over the sprites and colors just set before the finished picture appears.
play_level:
        pha
        jsr hal_blank
        pla
        jsr core_level_init
        lda lvl
        jsr hal_load_level
        jsr core_prepare_sprites
        jsr hal_update_sprites
        ldx #3
        jsr wait_x
        jsr hal_unblank
        lda #%00001111
        sta $d015                       ; sprites 0-3 on (hero and enemy, each overlay + base); hal_update_sprites sets the same again
.f:     jsr hal_wait_frame
        jsr hero_update
        jsr enemy_update
        jsr core_prepare_sprites
        jsr hal_update_sprites
        lda lvl_done
        beq .f
        ; Door reached: wait briefly, jingle, next level
        lda cur
        cmp #3
        beq +
        lda #6
        jsr hal_sfx
+       ldx #70
        jsr wait_x
        rts

; ---------------------------------------------------------------- Hardware layer, game logic, tables and music
; The order does not matter (the assembler resolves forward references); all that matters is that the code ends before $4000 (VIC bank 1),
; because the screen ($4400) and the sprite pointers ($47F8) are there; it currently ends at $2F2E.
.include "hal_mega65.asm"
.include "lib/core.asm"
.include "lib/levels.inc"

maps_lo: .byte <lv1_map, <lv2_map, <lv3_map, <lv4_map     ; tile map per level (240 bytes, from graphics/lv?.vctiles); hal_load_level
maps_hi: .byte >lv1_map, >lv2_map, >lv3_map, >lv4_map     ; copies the selected one to LMAP

music_runtime                           ; subroutines of the music (music_play ...), once behind the main program

; ---------------------------------------------------------------- Data at fixed addresses
; The VIC only sees the 16 KB of its bank 1 ($4000-$7FFF), so the character set ($6000) and sprites ($6800) are located exactly here; the screen
; is at $4400 (see hal_init, $D018). The .assert lines check that the
; exported sprite sets join up without gaps (hero 14 frames = 896 bytes, enemy 6 frames = 384 bytes).
.org $6000
.include "graphics/chars.vcchar"
.org $6800
.include "graphics/hero_base.vcsprite"
.include "graphics/hero_over.vcsprite"
.include "graphics/enemy_base.vcsprite"
.include "graphics/enemy_over.vcsprite"
.assert hero_over == $6b80
.assert enemy_base == $6f00
.assert enemy_over == $7080
.org $7200
.include "graphics/title.vcscreen"
.include "graphics/lv1.vctiles"
.include "graphics/lv2.vctiles"
.include "graphics/lv3.vctiles"
.include "graphics/lv4.vctiles"
.include "music/tune.vcsong"
