; =====================================================================================================================
; jumprun.asm - "Hugo & Gumbo": self-playing jump-and-run demo for the C64 (main program)
; =====================================================================================================================
;
; FLOW (endless):    title picture (8 seconds)  ->  scene 1 meadow -> scene 2 cave -> scene 3 castle -> scene 4 clouds
;                    ->  finale (fanfare)  ->  the title picture again.
;   There is no control: the "autopilot" (core.asm) guides the hero Hugo, the game logic makes the enemy Gumbo
;   run after him.  Music and sound effects play the whole time.
;
; STRUCTURE OF THE SOURCES
;   jumprun.asm              this main program (flow control, title picture)
;   hal_c64.asm              hardware layer: VIC-II (picture, sprites), SID (sound), interrupt
;   lib/core.asm             game logic (platform neutral; own copy for this project, independent of the other systems)
;   lib/music.inc            player routine for the tracker music (SID, 3 voices; adapted here for sound effects)
;   lib/levels.inc           tables: colours, start positions, autopilot scripts, texts
;                            (GENERATED by tools/gen_jumprun_c64.py from the art data tools/jumprun_art.py)
;   graphics/*, music/       project files of the editors: character set, tile set hg, screen bank levels (4 scenes), title picture, sprites, song
;                            (when building, the assembler converts them itself where they are included below)
;
; MEMORY MAP
;   $0801-$1F81  program (BASIC starter + code; in this version up to $16BD)     $1F82-$1FFF  tables of the tile set (hg_props ...)
;   $2000-$27FF  character set (from chars.vcchar)         $2800-$31FF  sprites (4 sets, see below)
;   $3200-...    title picture, maps of the scenes, music data, then the subroutines of the tile library (tiles_runtime)
;   $C000-$C0EF  scene map in RAM (LMAP)
;   Zero page:  $10-$43 game logic (core.asm), $50-$56 HAL, $58-$5F tile library, $F7-$FA music
;   Screen memory (screen $0400, sprite pointers $07F8, colour RAM $D800) and VIC bank 0: see hal_c64.asm.
; =====================================================================================================================
.target c64                             ; target system: Commodore 64
.cpu 6510 { illegals = deny }           ; CPU 6510; undocumented instructions are forbidden
.branchlong auto                        ; branches that are too far are extended by the assembler itself (warning W203)

.const ZP   = $10                       ; zero page variables of the game logic start at $10
.const LMAP = $c000              ; scene map in RAM (240 bytes), coins are deleted from it

; Tile library: draws the tiles (tile_put) and the scenes (screen_select_a, screen_draw_all); the data come from the export
; of graphics/hg.vctiles (tile set) and graphics/levels.vcscreen (screen bank), the binding is below at tiles_use.
.const TILE_MAPRAM = LMAP               ; screen_select_a copies the map of a scene to LMAP (coins are deleted there)
.const TILE_ZP = $58                    ; zero page $58-$5F for the library (the music uses $F7-$FA)
#include <c64/tiles.asm>

.org $0801                              ; BASIC start address
.basicstub start                        ; creates the BASIC line "10 SYS <address of start>" so that RUN starts the program

.include "lib/music.inc"

; Program start (via BASIC line "SYS"): set up the hardware, start the music (music_init sets up the player routine for the
; exported song data).  There is no return to BASIC; the program never ends.
start:  jsr hal_init                    ; set up VIC, sprites and interrupt (interrupts stay blocked)
        music_init tune_order, tune_patterns, tune_ins, tune_speed, tune_rows, tune_patsize
        cli                             ; release interrupts now: from here on music and frame clock run
        jmp main                        ; main flow

; ---------------------------------------------------------------- Main flow
; cur = number of the current scene (0..3)
cur:    .byte 0


; main: the main flow.  Score to 0, show the title picture, play the four scenes one after another, finale, start again.
main:   lda #0
        sta sc0
        sta sc1
        sta sc2
        jsr show_title
        lda #0
        sta cur
.next:  lda cur
        jsr play_level
        inc cur
        lda cur
        cmp #4
        bcc .next
        ; Finale: fanfare, then back to the title picture
        lda #7
        jsr hal_sfx
        ldx #100
        jsr wait_x
        jsr hal_blank
        ldx #20
        jsr wait_x
        jmp main

; wait_x: waits X frames (X * 1/50 second, PAL).  X = 0 would give 256 frames.  X is saved around the call, because the
;   HAL interface does not guarantee that hal_wait_frame keeps X (this version changes only A).  Changes A, X (= 0) and flags.
wait_x:                          ; wait X frames
-       txa
        pha
        jsr hal_wait_frame
        pla
        tax
        dex
        bne -
        rts

; ---------------------------------------------------------------- Title picture (8 seconds = 400 frames)
; show_title: shows the title picture with the sky colours and multicolors of the first scene, the flashing notice
;   (row 18; flashing = alternating text colour and sky colour in the colour RAM row) and both
;   figures, which bob slightly up and down.  The counter tmr_h:tmr_l counts 400 frames down.
;   This subroutine accesses the VIC registers ($D022/$D023), the sky table skyc and the HAL's screen/colour RAM DIRECTLY
;   (the colour choice matches the start of hal_load_level); it is therefore not system neutral.  Changes all registers.
show_title:
        jsr hal_blank
        lda #0
        sta lvl
        tax
        lda lvl_mc1,x
        sta $d022
        lda lvl_mc2,x
        sta $d023
        lda lvl_sky0,x
        sta skyc
        lda lvl_sky1,x
        sta skyc+1
        lda lvl_sky2,x
        sta skyc+2
        lda lvl_sky3,x
        sta skyc+3
        lda lvl_sky4,x
        sta skyc+4
        lda lvl_sky5,x
        sta skyc+5
        jsr hal_title
        ; Notice (row 18, column 9, 21 characters), flashes via the colour
        ldx #0
-       lda txt_prompt,x
        sta SCREEN+18*40+9,x
        inx
        cpx #21
        bne -
        ; Hero left, enemy right, both standing: the state variables of the core are set by hand, core_level_init does not run here
        lda #24
        sta hx_l
        lda #0
        sta hx_h
        sta hx_f
        sta hdir
        sta hmode
        sta hatim
        sta ex_f
        sta eatim
        sta emode
        lda #160
        sta hy
        sta ey
        lda #<272
        sta ex_l
        lda #>272
        sta ex_h
        lda #1
        sta edir
        jsr core_prepare_sprites
        jsr hal_update_sprites
        jsr hal_unblank
        lda #<400                ; 400 frames
        sta tmr_l
        lda #>400
        sta tmr_h
.tf:    jsr hal_wait_frame
        ; Flashing: bit 5 of the counter alternates every 32 frames between yellow (7) and the sky colour cyan (3); both values below 8 = hires text
        lda tmr_l
        and #$20
        beq +
        lda #7
        jmp ++
+       lda #3
+      ldx #0
-       sta COLOR+18*40+9,x
        inx
        cpx #21
        bne -
        ; Figures bob slightly: bit 4 of the counter alternates every 16 frames, foot y = 160 or 161
        lda tmr_l
        lsr a
        lsr a
        lsr a
        lsr a
        and #1
        clc
        adc #160
        sta hy
        sta ey
        jsr core_prepare_sprites
        jsr hal_update_sprites
        lda tmr_l                       ; count the 16-bit counter down: if the low byte is 0, decrease the high byte first (borrow)
        bne +
        dec tmr_h
+       dec tmr_l
        lda tmr_l
        ora tmr_h                       ; both bytes 0? Then the 400 frames are over.
        bne .tf
        rts

; ---------------------------------------------------------------- Play one scene: A = 0..3
; play_level: screen off -> initialise the game logic for this scene -> load scene and colours -> screen on ->
;   per frame: wait for the end of the frame, move hero, move enemy, prepare values for the HAL, set sprites ->
;   when the autopilot has reached "END" (lvl_done), play the jingle (except after the last scene), wait 70 frames.
;   Input: A = scene number 0..3 (also in cur).  Changes all registers.  The three frames of waiting before hal_unblank give the
;   interrupt time to take over the sprites and colours just set before the finished picture appears.
play_level:
        pha
        jsr hal_blank
        pla
        jsr core_level_init
        lda lvl
        jsr hal_load_level
        jsr core_prepare_sprites
        jsr hal_update_sprites
        ldx #3
        jsr wait_x
        jsr hal_unblank
        lda #%00001111
        sta $d015                       ; sprites 0-3 (hero and enemy, each overlay + base) on; hal_update_sprites sets the same again
.f:     jsr hal_wait_frame
        jsr hero_update
        jsr enemy_update
        jsr core_prepare_sprites
        jsr hal_update_sprites
        lda lvl_done
        beq .f
        ; Door reached: wait briefly, jingle, next scene
        lda cur
        cmp #3
        beq +
        lda #6
        jsr hal_sfx
+       ldx #70
        jsr wait_x
        rts

; ---------------------------------------------------------------- Hardware layer, game logic, tables and music
; The order does not matter (the assembler resolves forward references); all that matters is that the code ends before $1F82, where the tables
; of the tile set begin (see below, .org $2000 - 126).
.include "hal_c64.asm"
.include "lib/core.asm"
.include "lib/levels.inc"

; Tile properties of the game logic (core.asm reads tile_attr,x): 0 empty, 1 solid (hg_p_solid), 2 ladder (hg_p_ladder) - from the tile set
.const tile_attr = hg_props
.assert hg_p_solid == 1 && hg_p_ladder == 2, "core.asm expects 1 = solid, 2 = ladder"

music_runtime                          ; subroutines of the music (music_play ...), once behind the main program

; ---------------------------------------------------------------- Data at fixed addresses
; The VIC sees only $0000-$3FFF of the bank, so the character set and sprites are located exactly here. The .assert lines check that the
; exported sprite sets follow each other without gaps (hero 14 frames = 896 bytes, enemy 6 frames = 384 bytes).
; The character set is the target character set hg_chars of the tile set (all 256 characters of chars.vcchar are pinned: tile characters, solid area,
; font). The export puts the tables of the set (6 x 21 bytes) before hg_chars; that is why the file begins 126 bytes before $2000.
.org $2000 - 126
.include "graphics/hg.vctiles"
.assert hg_chars == $2000
.org $2800
.include "graphics/hero_base.vcsprite"
.include "graphics/hero_over.vcsprite"
.include "graphics/enemy_base.vcsprite"
.include "graphics/enemy_over.vcsprite"
.assert hero_over == $2b80
.assert enemy_base == $2f00
.assert enemy_over == $3080
.org $3200
.include "graphics/title.vcscreen"
.include "graphics/levels.vcscreen"
.include "music/tune.vcsong"

; Binding of the library to tile set and screen bank, then the subroutines (tile_put = hal_put_tile, screen_select_a, screen_draw_all)
        tiles_use hg_c0, hg_col, hg_props, hg_tw, hg_th, hg_count, levels_screens_lo, levels_screens_hi, levels_lv1_tiles_w, levels_lv1_tiles_h
        tiles_runtime
