; =====================================================================================================================
; jumprun.asm - "Hugo & Gumbo": self-playing jump-and-run demo for the Commodore Plus/4 (main program)
; =====================================================================================================================
;
; FLOW (endless):   title picture (8 seconds) -> level 1 meadow -> level 2 cave -> level 3 castle -> level 4 clouds
;                    -> finale (fanfare) -> back to the title picture.   No controls: the autopilot (core.asm) leads Hugo.
;   The enemy Gumbo runs after Hugo (also in core.asm).  Music and sound effects play all the time in the background, from the
;   raster interrupt of the HAL; the main program itself only computes one frame after the other (clock: 50 frames per second, PAL).
;
; STRUCTURE OF THE SOURCES
;   jumprun.asm              this main program (flow control, title picture)
;   hal_plus4.asm            hardware layer: TED (picture, character sprites, sound), raster interrupt
;   lib/core.asm             game logic (platform neutral; own copy in this project, independent of the other systems)
;   lib/levels.inc           tables, figure images, music (GENERATED by tools/gen_jumprun_plus4.py)
;   graphics/*               project files of the editors: character set chars.vcchar, tile set hg.vctiles, screen bank levels.vcscreen, title picture title.vcscreen
;                            (converted during the build where it is included below)
;
; MEMORY MAP
;   $1001-$3FFF  program (BASIC starter + code)   $4000-$47FF  character set   $4800-...  tables, figure images, music
;   $6800-...    title picture and tile maps      $9000 level map (LMAP)   $9400 background copy   $0800 color RAM   $0C00 screen
;   Zero page: $80-$B3 game logic (ZP), $C0-$E3 HAL.   The Plus/4 starts BASIC programs at $1001 (BASIC memory without expansion);
;   below $4000 there is therefore room for about 12 KB of code, and the character set must sit on a 1 KB boundary ($4000 = 16 * 1024).
;   The TED sees the RAM only as a whole: picture, character set and color RAM lie in the same RAM as code and data; there is no
;   "bank" as on the C64.  The tables from $4800 and the picture data from $6800 are just ordinary data.
;
; COLORS: TED color value = luminance * 16 + hue.  In color RAM bit 3 (+8) is added for "multicolor" (hue then only 0..7).
;   All color values of the tables in lib/levels.inc are produced in the generator tools/gen_jumprun_plus4.py by this formula.
; =====================================================================================================================
.target plus4                           ; target system: Commodore Plus/4 (BASIC start at $1001)
.cpu 7501                               ; CPU 7501 (like 6502, in the TED computer; nothing special here)
.branchlong auto                        ; the assembler lengthens conditional branches that are too far itself (warning W203)

.const ZP   = $80                       ; zero page variables of the game logic start at $80 (core.asm places them from here, up to $B3)
.const LMAP = $9000                     ; level map in RAM (240 bytes = 20 x 12 tiles); coins are deleted from it

.org $1001                              ; BASIC start address of the Plus/4
.basicstub start                        ; creates the BASIC line "10 SYS <address of start>" so that RUN starts the program

; Program start (via BASIC line "SYS"): set up hardware (the operating system is switched off), enable interrupts, main flow.
;   From the cli on, music and sky bars (raster interrupt) run by themselves; hal_init deliberately leaves the interrupts disabled
;   until everything is set up.  There is no return to BASIC: the ROM is switched off.
start:  jsr hal_init
        cli
        jmp main

; ---------------------------------------------------------------- Main flow
; cur = number of the running level (0..3)
cur:    .byte 0

; main: score to 0, title picture, four levels one after another, finale, from the start.
main:   lda #0
        sta sc0
        sta sc1
        sta sc2
        jsr show_title
        lda #0
        sta cur
.next:  lda cur
        jsr play_level
        inc cur
        lda cur
        cmp #4
        bcc .next
        lda #7                          ; finale: fanfare (sound effect 7, 60 frames)
        jsr hal_sfx
        ldx #100                        ; let it stand for 2 seconds
        jsr wait_x
        jsr hal_blank                   ; screen off, short pause (0.4 s), then everything starts again with the title picture
        ldx #20
        jsr wait_x
        jmp main

; wait_x: waits X frames (X * 1/50 second, PAL).  X = 0 would give 256 frames.  X is saved around the call, because the
;   HAL interface does not guarantee that hal_wait_frame preserves X (this version changes only A).  Changes A, X (= 0) and flags.
wait_x: txa
        pha
        jsr hal_wait_frame
        pla
        tax
        dex
        bne wait_x
        rts

; ---------------------------------------------------------------- Title picture (8 seconds = 400 frames)
; colors of the first level, hint text (blinks: text and blanks alternately), both figures bob.
;   The picture is built with the screen off (hal_blank) so that the rebuild is not seen.
;   The blinking is done here by rewriting screen AND background copy: the copy must follow, so that the
;   character sprites (which read the background from it) do not write the old text back onto the screen.
;   This subroutine accesses internals of the HAL DIRECTLY (SCREEN, BGS, skyc, TED color registers via .colors) and sets the
;   state variables of the core by hand (core_level_init does not run here); it is therefore not system neutral.  Changes all registers.
show_title:
        jsr hal_blank
        lda #0
        sta lvl                         ; the title picture uses colors and sky of level 1
        jsr .colors
        jsr hal_title                   ; 24 rows of title picture to screen, background copy and color RAM; forget the figure state
        lda #0                          ; hero on the left, enemy on the right, both standing
        sta hx_h
        sta hx_f
        sta hdir
        sta hmode
        sta hatim
        sta ex_f
        sta eatim
        sta emode
        lda #24                         ; hero: x = 24, foot y = 160 (coordinates of the game logic, one pixel = 2 dots)
        sta hx_l
        lda #160
        sta hy
        sta ey
        lda #<272                       ; enemy: x = 272 (16 bit), looks to the left (edir = 1)
        sta ex_l
        lda #>272
        sta ex_h
        lda #1
        sta edir
        jsr core_prepare_sprites        ; game logic: provide image numbers and position of the figures for the HAL (h_px_l etc.)
        jsr hal_update_sprites          ; compose the character sprites once (still with the screen off)
        jsr hal_unblank
        lda #<400                       ; 400 frames = 8 seconds
        sta tmr_l
        lda #>400
        sta tmr_h
.tf:    jsr hal_wait_frame
        lda tmr_l                       ; blinking: bit 5 of the counter selects text or blanks
        and #$20                        ; 32 frames on, 32 frames off
        beq .blank
        ldx #20                         ; text "DEMO - NICHT SPIELBAR" (21 characters, German text in the data) in row 18, from column 9
-       lda txt_prompt,x
        sta SCREEN+18*40+9,x
        sta BGS+18*40+9,x
        dex
        bpl -
        jmp .wip
.blank: ldx #20                         ; fill the same place with blanks
        lda #CH_BLANK
-       sta SCREEN+18*40+9,x
        sta BGS+18*40+9,x
        dex
        bpl -
.wip:   lda tmr_l                       ; figures bob slightly (bit 4 of the counter)
        lsr a
        lsr a
        lsr a
        lsr a
        and #1
        clc
        adc #160                        ; foot y = 160 or 161: the figures hop by one pixel line
        sta hy
        sta ey
        jsr core_prepare_sprites
        jsr hal_update_sprites          ; composes anew only if y has changed (hal_update_sprites compares)
        lda tmr_l                       ; count the 16-bit counter down: when tmr_l = 0, first the borrow to tmr_h
        bne +
        dec tmr_h
+       dec tmr_l
        lda tmr_l
        ora tmr_h
        bne .tf
        rts
; .colors: set color registers and sky bars of level lvl (the title picture uses the colors of the first level)
;   Color 1 / color 2 go into the TED registers ($FF16/$FF17) and apply to the whole picture; the six bar colors are stored in
;   skyc, from where the raster interrupt of the HAL writes them to $FF15 (background).
.colors:                                ; input lvl (level number); changes A, X
        ldx lvl
        lda lvl_mc1,x
        sta TED_MC1
        lda lvl_mc2,x
        sta TED_MC2
        lda lvl_sky0,x
        sta skyc
        lda lvl_sky1,x
        sta skyc+1
        lda lvl_sky2,x
        sta skyc+2
        lda lvl_sky3,x
        sta skyc+3
        lda lvl_sky4,x
        sta skyc+4
        lda lvl_sky5,x
        sta skyc+5
        rts

; ---------------------------------------------------------------- Play one level: A = 0..3
; play_level: builds the level with the screen off, switches it on and then, every frame (1/50 s), executes one step of
;   hero (autopilot) and enemy until the game logic reports lvl_done (Hugo has reached the door).
;   Input: A = level number 0..3 (also in cur).  Changes all registers.
play_level:
        pha
        jsr hal_blank
        pla
        jsr core_level_init             ; game logic: start positions, script of the level (A = level number)
        lda lvl
        jsr hal_load_level              ; colors, sky, map (LMAP), tiles, status lines
        jsr core_prepare_sprites
        jsr hal_update_sprites
        ldx #3                          ; wait 3 frames before the finished picture is shown
        jsr wait_x
        jsr hal_unblank
.f:     jsr hal_wait_frame              ; wait for the frame clock of the raster interrupt
        jsr hero_update                 ; game logic: one step of the autopilot
        jsr enemy_update                ; game logic: one step of the enemy
        jsr core_prepare_sprites        ; convert logic coordinates to the values of the HAL
        jsr hal_update_sprites          ; compose the character sprites anew if something has moved
        lda lvl_done
        beq .f
        lda cur                         ; door reached: jingle (not after the last level), wait briefly
        cmp #3
        beq +
        lda #6
        jsr hal_sfx
+       ldx #70                         ; 1.4 seconds final pause
        jsr wait_x
        rts

; Include the sources: the HAL (TED) and the common game logic.  Both lie in the program area below $4000
; (state of this version: program $1001-$1DD6, character set $4000-$47FF, tables $4800-$5EEC, picture data $6800-$7123).
.include "hal_plus4.asm"
.include "lib/core.asm"

; Tile properties of the game logic (core.asm reads tile_attr,x): 0 empty, 1 solid (hg_p_solid), 2 ladder (hg_p_ladder) - from the tile set
.const tile_attr = hg_props
.assert hg_p_solid == 1 && hg_p_ladder == 2, "core.asm expects 1 = solid, 2 = ladder"

; ---- Data at fixed addresses (the files from graphics/ are converted where they are included)
.org $4000 - 105                       ; character set: 256 characters * 8 bytes; the TED fetches it from here (register $FF13 = $42);
.include "graphics/hg.vctiles"          ;   the export of the tile set puts the tables before hg_chars (4 x 21 characters, 21 properties = 105 bytes);
.assert hg_chars == $4000, "character set must be at $4000 (tile set tables before it, see .org)"
                                        ;   hg_chars is chars.vcchar (all 256 characters pinned); the characters $E0-$F4 are the pool of the character sprites
.org $4800                              ; tables and figure images (made by the generator), music
.include "lib/levels.inc"
.org $6800                              ; title picture (title_chars) and the maps of the screen bank levels (levels_map0..3, levels_screens_lo/hi)
.include "graphics/title.vcscreen"
.include "graphics/levels.vcscreen"
